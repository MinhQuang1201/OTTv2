#!/usr/bin/env node
/**
 * Normalised-source hashes of the public reference corpus (plan §8.5, layer 1). A submission whose normalised hash
 * matches one of these is flagged for the organisers. The API cannot read repository files at run time, so the hashes
 * are generated into apps/bot-cup-api/src/reference-hashes.mjs; tests/bot-cup-core.test.js fails when it is stale.
 *
 *   node scripts/bot-cup/reference-hashes.mjs          # rewrite the generated module
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { languageForFilename, normalizeSource } from "../../packages/bot-cup-core/src/submission.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const OUTPUT = "apps/bot-cup-api/src/reference-hashes.mjs";

export const REFERENCE_FILES = Object.freeze([
  "packages/game-core/src/ai.js",
  "bots/sentinel.mjs",
  "bots/strategist.mjs",
  "sdk/arena/examples/first_legal.py",
  "sdk/arena/examples/first_legal.mjs",
  "sdk/arena/python/ott_bot.py",
  "sdk/bot-cup/python/bot.py",
  "sdk/bot-cup/js/bot.mjs"
]);

export function computeReferenceHashes() {
  return REFERENCE_FILES.map((file) => {
    const text = fs.readFileSync(path.join(ROOT, file), "utf8");
    const normalized = normalizeSource(text, languageForFilename(file));
    return { file, normalizedHash: createHash("sha256").update(normalized, "utf8").digest("hex") };
  });
}

export function renderModule(entries) {
  const lines = entries.map(({ file, normalizedHash }) => `  ["${normalizedHash}", "${file}"]`).join(",\n");
  return [
    "// Generated by scripts/bot-cup/reference-hashes.mjs — do not edit. Regenerate after changing a reference file.",
    "// normalized_hash -> public file it came from (plan §8.5).",
    "export const REFERENCE_HASHES = new Map([",
    lines,
    "]);",
    ""
  ].join("\n");
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  fs.writeFileSync(path.join(ROOT, OUTPUT), renderModule(computeReferenceHashes()));
  console.log(`wrote ${OUTPUT}`);
}
