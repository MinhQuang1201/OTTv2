/**
 * Demo rehearsal on staging (plan §12 P9): 8 synthetic teams in their own event, so the staging event used for
 * registration tests is never frozen. Teams are written straight into D1 (no OTP mail to made-up MSSV) with a session each;
 * their bots are uploaded through the API like a team would; organisers drive the rest from the admin site or `admin`.
 *
 *   node scripts/bot-cup/rehearsal.mjs seed [--freeze-in <minutes>]   event + teams + sessions on the staging D1
 *   node scripts/bot-cup/rehearsal.mjs upload --api <rehearsal API origin>
 *   node scripts/bot-cup/rehearsal.mjs admin --admin <admin origin> --email <admin> <METHOD> <path> [json]
 *
 * Bots live in var/bot-cup/rehearsal/bots/ (outside git: the repository is public and one of them is a translation of
 * ai.js). Session tokens go to var/bot-cup/rehearsal/sessions.json. Staging only: production is refused.
 */
import crypto from "node:crypto";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { nameKey } from "../../packages/bot-cup-core/src/index.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const DIR = path.join(ROOT, "var/bot-cup/rehearsal");
export const EVENT_ID = "rehearsal-demo";
const WEB_ORIGIN = "https://ottv2-staging.vercel.app";
const DAY = 24 * 60 * 60 * 1000;

/** The 8 teams of the plan: one broken bot, one copied pair (t2 → t3), one translation of ai.js (t1), four others. */
export const TEAMS = Object.freeze([
  { key: "t1", name: "Đội Mặt Trời", file: "t1-ai-port.py", planted: "ai.js medium dịch sang Python" },
  { key: "t2", name: "Đội Sao Mai", file: "t2-minimax.mjs", planted: null },
  { key: "t3", name: "Đội Bình Minh", file: "t3-minimax-copy.mjs", planted: "chép của Đội Sao Mai (đổi tên, đảo hàm)" },
  { key: "t4", name: "Đội Hoa Sen", file: "t4-greedy.py", planted: null },
  { key: "t5", name: "Đội Phượng Hoàng", file: "t5-guard.mjs", planted: null },
  { key: "t6", name: "Đội Gió Lốc", file: "t6-broken.py", planted: "cố tình hỏng ngoài bản đồ classic" },
  { key: "t7", name: "Đội Sông Hồng", file: "t7-lookahead.py", planted: null },
  { key: "t8", name: "Đội Mầm Non", file: "t8-template.py", planted: null }
]);

function option(name, fallback = null) {
  const index = process.argv.indexOf(`--${name}`);
  return index > 0 ? process.argv[index + 1] : fallback;
}

const sqlText = (value) => `'${String(value).replace(/'/g, "''")}'`;

export function seedSql({ now, freezeAt, tokens }) {
  const lines = [
    "-- P9 rehearsal event (generated by scripts/bot-cup/rehearsal.mjs).",
    `INSERT INTO events (id, name, mode, phase, registration_opens_at, registration_closes_at, practice_opens_at, code_freeze_at, finals_at, config_json)
VALUES (${sqlText(EVENT_ID)}, 'OTT Bot Cup (diễn tập P9)', 'demo', 'registration', ${now - 2 * DAY}, ${now - DAY}, ${now - DAY}, ${freezeAt}, ${freezeAt + DAY}, '{}')
ON CONFLICT (id) DO UPDATE SET code_freeze_at = excluded.code_freeze_at, finals_at = excluded.finals_at;`
  ];
  TEAMS.forEach((team, index) => {
    const id = `rehearsal-${team.key}`;
    const mssv = `2699${String(index + 1).padStart(4, "0")}`;
    lines.push(
      `INSERT OR IGNORE INTO teams (id, event_id, handle, display_name, display_key, kind, status, captain_mssv, password_hash, created_at, verified_at, active_at)
VALUES (${sqlText(id)}, ${sqlText(EVENT_ID)}, ${sqlText(`rh-${team.key}`)}, ${sqlText(team.name)}, ${sqlText(nameKey(team.name))}, 'solo', 'active', ${sqlText(mssv)}, 'disabled', ${now}, ${now}, ${now});`,
      `INSERT OR IGNORE INTO members (event_id, mssv, team_id, full_name, email, role, status, show_name, consent_at, created_at, confirmed_at)
VALUES (${sqlText(EVENT_ID)}, ${sqlText(mssv)}, ${sqlText(id)}, 'Thành viên diễn tập', ${sqlText(`rehearsal-${team.key}@ottcup.test`)}, 'captain', 'confirmed', 0, ${now}, ${now}, ${now});`,
      `INSERT INTO sessions (id_hash, team_id, created_at, expires_at, user_agent) VALUES (${sqlText(crypto.createHash("sha256").update(tokens[team.key]).digest("hex"))}, ${sqlText(id)}, ${now}, ${now + 7 * DAY}, 'rehearsal');`
    );
  });
  return `${lines.join("\n")}\n`;
}

function wrangler(args) {
  const npx = process.platform === "win32" ? "npx.cmd" : "npx";
  const result = spawnSync(npx, ["wrangler", ...args], { cwd: ROOT, stdio: "inherit", shell: process.platform === "win32" });
  if (result.status !== 0) throw new Error(`wrangler ${args[0]} failed`);
}

async function seed() {
  const now = Date.now();
  const freezeAt = now + Number(option("freeze-in", "40")) * 60 * 1000;
  const tokens = Object.fromEntries(TEAMS.map((team) => [team.key, crypto.randomBytes(32).toString("base64url")]));
  fs.mkdirSync(DIR, { recursive: true });
  const file = path.join(DIR, "seed.sql");
  fs.writeFileSync(file, seedSql({ now, freezeAt, tokens }));
  wrangler(["d1", "execute", "ottv2-bot-cup-staging", "--remote", "--env", "staging", "--config", "apps/bot-cup-api/wrangler.jsonc", "--file", path.relative(ROOT, file)]);
  fs.writeFileSync(path.join(DIR, "sessions.json"), JSON.stringify(tokens, null, 2), { mode: 0o600 });
  console.log(JSON.stringify({ event: EVENT_ID, codeFreezeAt: new Date(freezeAt).toISOString(), teams: TEAMS.length }));
}

async function upload() {
  const api = option("api");
  if (!/^https:\/\/[^/]+$/.test(api ?? "") || api.includes("ottv2-bot-cup-api.")) throw new Error("--api must be the rehearsal Worker origin");
  const tokens = JSON.parse(fs.readFileSync(path.join(DIR, "sessions.json"), "utf8"));
  const result = {};
  for (const team of TEAMS) {
    const bytes = fs.readFileSync(path.join(DIR, "bots", team.file));
    const form = new FormData();
    form.append("file", new Blob([bytes]), team.file.replace(/^t\d-/, "bot-"));
    const response = await fetch(`${api}/api/t/submissions`, { method: "POST", headers: { origin: WEB_ORIGIN, cookie: `__Host-ottcup_session=${tokens[team.key]}` }, body: form });
    const body = await response.json();
    if (response.status !== 201) throw new Error(`${team.key}: ${response.status} ${JSON.stringify(body)}`);
    result[team.key] = { team: team.name, submission: body.submission.id, sha256: body.submission.sha256, flags: body.submission.flags ?? [] };
  }
  fs.writeFileSync(path.join(DIR, "submissions.json"), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
}

async function admin() {
  const base = option("admin");
  const email = option("email");
  const args = process.argv.slice(process.argv.indexOf(email) + 1);
  const [method, url, json] = args;
  const { totpCode } = await import(pathToFileURL(path.join(ROOT, "apps/bot-cup-admin/src/auth.mjs")).href);
  const text = fs.readFileSync(path.join(ROOT, "var/bot-cup", `admin-${email}.txt`), "utf8");
  const field = (name) => text.match(new RegExp(`^${name}: (.+)$`, "m"))[1].trim();
  const login = await fetch(`${base}/admin-api/login`, {
    method: "POST",
    headers: { "content-type": "application/json", origin: base },
    body: JSON.stringify({ email, password: field("password"), totp: await totpCode(field("totp secret"), Date.now()) })
  });
  if (login.status !== 200) throw new Error(`login ${login.status} ${await login.text()}`);
  const cookie = login.headers.get("set-cookie").split(";")[0];
  const response = await fetch(`${base}/admin-api${url}`, {
    method,
    headers: { cookie, ...(json ? { origin: base, "content-type": "application/json" } : {}) },
    body: json || undefined
  });
  console.log(response.status, await response.text());
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const command = process.argv[2];
  const run = { seed, upload, admin }[command];
  if (!run) {
    console.error("usage: rehearsal.mjs seed|upload|admin …");
    process.exit(1);
  }
  run().catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
